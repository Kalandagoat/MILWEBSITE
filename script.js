/* ==========================================================
   OPEN ESSAY
========================================================== */

function openEssay(essayID) {

    const essay = essays[essayID];

    if (!essay) {
        return;
    }

    const modal = document.getElementById("essayModal");

    const content = document.getElementById("essayModalContent");

    content.innerHTML = `

        <div class="essay-category">
            ${essay.category}
        </div>

        <h2>
            ${essay.title}
        </h2>

        ${essay.content}

    `;

    modal.classList.add("active");

    document.body.style.overflow = "hidden";
}



/* ==========================================================
   CLOSE ESSAY
========================================================== */

function closeEssay() {

    const modal = document.getElementById("essayModal");

    modal.classList.remove("active");

    document.body.style.overflow = "auto";
}



/* ==========================================================
   CLOSE WHEN CLICKING OUTSIDE
========================================================== */

document.getElementById("essayModal").addEventListener(
    "click",
    function(event) {

        if (event.target === this) {

            closeEssay();

        }

    }
);



/* ==========================================================
   ESCAPE KEY
========================================================== */

document.addEventListener(
    "keydown",
    function(event) {

        if (event.key === "Escape") {

            closeEssay();

        }

    }
);



/* ==========================================================
   NAVBAR SCROLL EFFECT
========================================================== */

window.addEventListener(
    "scroll",
    function() {

        const navbar =
            document.querySelector(".navbar");

        if (window.scrollY > 50) {

            navbar.style.boxShadow =
                "0 5px 25px rgba(0,0,0,0.08)";

        } else {

            navbar.style.boxShadow = "none";

        }

    }
);
